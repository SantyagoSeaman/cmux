#!/usr/bin/env python3
"""Progress report of the Linux Swift tier, from swift-tier.sh and swift-shared.sh receipts (p15-oracle-151).

Stdlib only, safe under `python3 -I`. A report, not a gate: it exits 0 whatever the numbers are, and 2 only
when it finds no receipt or cannot write the doc. Every number comes from a receipt
(`cmux-linux-swift-receipt/1`, written by errors_queue.py); the script counts nothing itself, so a test total
here is a count of executed tests, never a grep of `@Test`.

For each receipt it gives the targets built, the tests executed, the build and test wall times and the
`--measure-incremental` time, and holds the receipts of each suite against the done checks of
plans/cmux-next/chrome-parity/p15-oracle.md section 5 (checks 1-3). Each check reads the newest receipt that
holds its number: the totals and the build time come from the newest run of the whole plan (a receipt with the
suite's build phase, or one whose setup failed), the incremental time from the newest receipt with an
`incremental` block. A `swift-tier.sh --only` run records no `build-all` phase, so it never stands in for the
tier. Chrome reads its bots' progress the same way: the numbers come from the step results the builders upload
(test-results JSON, third_party/blink/tools/blinkpy/web_tests/models/test_run_results.py), not from a count of
the sources.

Usage:
  tier-report.py [RECEIPT_OR_DIR ...] [--json] [--cases] [--history N] [--write-doc [FILE]]

  RECEIPT_OR_DIR  receipt files, or folders searched for them (default: $CMUX_LINUX_OUT, else $TMPDIR/oracle,
                  else /tmp/oracle; plus /tmp/oracle/linux-tier.json and /tmp/oracle/linux-shared.json,
                  the done-check paths)
  --json          print the report as JSON
  --cases         also list each test target or package with its executed tests (done check 2 lists each
                  package's count)
  --history N     receipts in the history table (default 20; 0 for all)
  --write-doc     replace the results table between the tier-report.py markers of FILE
                  (default plans/cmux-next/oracle-DESIGN.md) with the receipts the done checks read
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import os
import sys
from pathlib import Path
from typing import Iterable, Sequence

REPO_ROOT = Path(__file__).resolve().parents[3]
DESIGN_DOC = REPO_ROOT / "plans" / "cmux-next" / "oracle-DESIGN.md"
RECEIPT_SCHEMA = "cmux-linux-swift-receipt/1"
DONE_CHECK_PATHS = (Path("/tmp/oracle/linux-tier.json"), Path("/tmp/oracle/linux-shared.json"))
MAX_RECEIPT_BYTES = 64 * 1024 * 1024
DOC_BEGIN = "<!-- BEGIN tier-report.py: generated by scripts/cmux-next/linux/tier-report.py --write-doc -->"
DOC_END = "<!-- END tier-report.py -->"
TOTALS = "totals"
INCREMENTAL = "incremental"


@dataclasses.dataclass(frozen=True)
class Goal:
    """One done-check number (p15-oracle.md section 5)."""

    label: str
    field: str  # a key of Row
    limit: float
    at_least: bool  # True: value >= limit; False: value < limit
    source: str = TOTALS  # the receipt that holds the number (Selection.source)


# Done checks 1-3 of p15-oracle.md section 5, per suite.
GOALS: dict[str, tuple[Goal, ...]] = {
    "swift-tier": (
        Goal("CmuxNext source targets built", "built", 30, True),
        Goal("test targets built", "test_targets_built", 15, True),
        Goal("tests executed", "tests_executed", 1500, True),
        Goal("build-all wall seconds (clean scratch)", "build_seconds", 600, False),
        Goal("incremental build seconds", "incremental_seconds", 30, False, INCREMENTAL),
    ),
    "swift-shared": (
        Goal("Shared/iOS packages built", "built", 26, True),
        Goal("tests executed", "tests_executed", 2900, True),
    ),
}
# The wall-time phase that is the suite's build: swift-tier.sh records `build-all` (the one
# `swift build --build-tests`, only when no --only is given), swift-shared.sh `build-and-test`.
BUILD_PHASE = {"swift-tier": "build-all", "swift-shared": "build-and-test"}


class ReceiptError(Exception):
    """A file names the receipt schema but lacks a field the report reads."""


@dataclasses.dataclass(frozen=True)
class Row:
    path: str
    suite: str
    sha: str
    dirty: bool
    sanitize: str
    started_at: str
    toolchain: str
    ok: bool
    built: int  # source targets (tier) or packages (shared)
    planned: int
    failed: int
    blocked: int
    test_targets_failed: int  # test targets that failed or timed out to compile
    test_targets_blocked: int
    setup_failed: tuple[str, ...]  # setup steps (resolve, dump-package, ...) that failed: nothing after them ran
    test_targets_built: int
    test_targets_run: int
    tests_executed: int
    tests_passed: int
    tests_failed: int
    tests_skipped: int
    build_seconds: float | None
    test_seconds: float | None
    total_seconds: float
    incremental_target: str
    incremental_seconds: float | None
    incremental_status: str
    unexpected: int
    errors_queue: int
    cases: tuple[tuple[str, str, int, float], ...]  # (name, run status, tests executed, linux share)

    @property
    def key(self) -> tuple[str, str, str, str]:
        return (self.suite, self.sha, self.started_at, self.sanitize)

    @property
    def holds_totals(self) -> bool:
        """The run covered the suite's whole plan: it recorded the build phase, or its setup failed first."""
        return self.build_seconds is not None or bool(self.setup_failed)

    @property
    def red(self) -> bool:
        """A setup step, a source target or a test target failed or was blocked."""
        return bool(
            self.setup_failed or self.failed or self.blocked or self.test_targets_failed or self.test_targets_blocked
        )


def _count(value: object) -> int:
    return len(value) if isinstance(value, list) else 0


def row_from_receipt(receipt: dict, path: str) -> Row:
    try:
        suite = receipt["suite"]
        targets = receipt["targets"]
        test_targets = receipt["test_targets"]
        tests = receipt["tests"]
        walls = receipt["wall_seconds"]
        cases = receipt.get("cases") or {}
        if suite == "swift-shared":
            packages = receipt["packages"]
            built = _count(packages.get("built"))
            failed = _count(packages.get("failed"))
            blocked = 0
            planned = built + failed + _count(packages.get("skipped")) + _count(targets.get("missing"))
        else:
            built = _count(targets.get("built"))
            failed = _count(targets.get("failed")) + _count(targets.get("missing"))
            blocked = _count(targets.get("blocked"))
            planned = built + failed + blocked + _count(targets.get("skipped"))
        incremental = receipt.get("incremental") or {}
        case_rows = tuple(
            (name, str(c.get("run", "")), int(c.get("tests", 0)), float(c.get("linux_share", 0.0)))
            for name, c in sorted(cases.items())
            if c.get("kind") in ("test", "package") and c.get("run")
        )
        return Row(
            path=path,
            suite=suite,
            sha=str(receipt.get("sha", "")),
            dirty=bool(receipt.get("dirty")),
            sanitize=str(receipt.get("sanitize") or ""),
            started_at=str(receipt.get("started_at", "")),
            toolchain=str(receipt.get("toolchain", "")),
            ok=bool(receipt.get("ok")),
            built=built,
            planned=planned,
            failed=failed,
            blocked=blocked,
            test_targets_failed=_count(test_targets.get("failed")),
            test_targets_blocked=_count(test_targets.get("blocked")),
            setup_failed=tuple(str(s) for s in (receipt.get("setup") or {}).get("failed") or ()),
            test_targets_built=_count(test_targets.get("built")),
            test_targets_run=_count(test_targets.get("run")),
            tests_executed=int(tests["executed"]),
            tests_passed=int(tests["passed"]),
            tests_failed=int(tests["failed"]),
            tests_skipped=int(tests.get("skipped", 0)),
            build_seconds=walls.get(BUILD_PHASE.get(suite, "")),
            test_seconds=walls.get("test"),
            total_seconds=round(sum(float(v) for v in walls.values()), 2),
            incremental_target=str(incremental.get("target", "")),
            incremental_seconds=incremental.get("seconds") if incremental.get("status") == "pass" else None,
            incremental_status=str(incremental.get("status", "")),
            unexpected=_count(receipt.get("unexpected")),
            errors_queue=int((receipt.get("errors_queue") or {}).get("entries", 0)),
            cases=case_rows,
        )
    except (KeyError, TypeError, ValueError, AttributeError) as error:
        raise ReceiptError(f"{path}: not a readable {RECEIPT_SCHEMA} receipt ({error!r})") from error


def _candidates(paths: Iterable[Path]) -> Iterable[Path]:
    for path in paths:
        if path.is_file():
            yield path
        elif path.is_dir():
            yield from sorted(p for p in path.rglob("*.json") if p.is_file())


def load_rows(paths: Sequence[Path], warnings: list[str]) -> list[Row]:
    """Receipts under PATHS, one row per run (a receipt copied to two places counts once), oldest first."""
    rows: dict[tuple[str, str, str, str], Row] = {}
    for path in _candidates(paths):
        try:
            if path.stat().st_size > MAX_RECEIPT_BYTES:
                continue
            with path.open(encoding="utf-8") as handle:
                data = json.load(handle)
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            continue  # not a receipt: logs and other JSON share these folders
        if not isinstance(data, dict) or data.get("schema") != RECEIPT_SCHEMA:
            continue
        try:
            row = row_from_receipt(data, str(path))
        except ReceiptError as error:
            warnings.append(str(error))
            continue
        rows.setdefault(row.key, row)
    return sorted(rows.values(), key=lambda r: (r.started_at, r.suite, r.sanitize))


def default_paths(env: dict[str, str]) -> list[Path]:
    out = env.get("CMUX_LINUX_OUT") or str(Path(env.get("TMPDIR") or "/tmp") / "oracle")
    paths = [Path(out)]
    paths += [p for p in DONE_CHECK_PATHS if p.parent != Path(out)]
    return paths


@dataclasses.dataclass(frozen=True)
class Selection:
    """The receipts the done checks of one (suite, sanitizer) pair read."""

    suite: str
    sanitize: str
    newest: Row
    totals: Row | None  # the newest receipt that Row.holds_totals
    incremental: Row | None  # the newest receipt with an incremental block

    def source(self, name: str) -> Row | None:
        return self.incremental if name == INCREMENTAL else self.totals

    def shown(self) -> list[tuple[Row, str]]:
        """The receipts the checks read, oldest first, with the checks each one feeds."""
        used: dict[str, list[str]] = {}
        rows: dict[str, Row] = {}
        for name in (TOTALS, INCREMENTAL):
            row = self.source(name)
            if row is not None:
                rows.setdefault(row.path, row)
                used.setdefault(row.path, []).append(name)
        if not rows:
            return [(self.newest, "none (subset run)")]
        return [(row, ", ".join(used[row.path])) for row in sorted(rows.values(), key=lambda r: r.started_at)]


def select(rows: Sequence[Row]) -> list[Selection]:
    """One Selection per (suite, sanitizer) pair, tier first. ROWS are oldest first."""
    groups: dict[tuple[str, str], list[Row]] = {}
    for row in rows:
        groups.setdefault((row.suite, row.sanitize), []).append(row)
    selections = []
    for (suite, sanitize), group in groups.items():
        totals = [r for r in group if r.holds_totals]
        incremental = [r for r in group if r.incremental_target]
        selections.append(
            Selection(
                suite=suite,
                sanitize=sanitize,
                newest=group[-1],
                totals=totals[-1] if totals else None,
                incremental=incremental[-1] if incremental else None,
            )
        )
    return sorted(selections, key=lambda s: (s.suite != "swift-tier", s.suite, s.sanitize))


def goal_results(selection: Selection) -> list[dict]:
    """The done-check numbers of SELECTION; a value no receipt has is `None`, never met."""
    results = []
    for goal in GOALS.get(selection.suite, ()):
        if selection.sanitize and goal.field in ("build_seconds", "incremental_seconds"):
            continue  # sanitized builds are slower by design; the time checks hold for the plain build
        row = selection.source(goal.source)
        value = None if row is None else getattr(row, goal.field)
        met = None if value is None else (value >= goal.limit if goal.at_least else value < goal.limit)
        if row is not None and goal.field == "build_seconds":
            # No receipt field says the scratch was new, and swift-tier.sh keeps it between runs, so a time
            # under the limit can be a warm rebuild: it never proves the clean-build check.
            met = False if row.red or met is False else None
        if row is not None and goal.field == "incremental_seconds" and row.incremental_status not in ("", "pass"):
            met = False  # the receipt has a failed, blocked or timed-out incremental build
        results.append(
            {
                "check": goal.label,
                "value": value,
                "limit": goal.limit,
                "at_least": goal.at_least,
                "met": met,
                "receipt": None if row is None else row.path,
                "receipt_started_at": None if row is None else row.started_at,
                "receipt_sha": None if row is None else row.sha,
            }
        )
    return results


# ------------------------------------------------------------------------------------- rendering


def _num(value: float | int | None) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:,.1f}"
    return f"{value:,}"


def _suite(suite: str, sanitize: str) -> str:
    return suite + (f" ({sanitize})" if sanitize else "")


def _sha(row: Row) -> str:
    return (row.sha[:12] or "?") + ("-dirty" if row.dirty else "")


def _incremental(row: Row) -> str:
    if not row.incremental_target:
        return "-"
    if row.incremental_seconds is None:
        return f"{row.incremental_status} ({row.incremental_target})"
    return f"{row.incremental_seconds:.1f} s ({row.incremental_target})"


def _table(header: Sequence[str], body: Iterable[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    lines += ["| " + " | ".join(cells) + " |" for cells in body]
    return lines


SUMMARY_HEADER = (
    "Suite",
    "Started (UTC)",
    "SHA",
    "Built / planned",
    "Failed",
    "Blocked",
    "Setup failed",
    "Test targets built / run (failed, blocked)",
    "Tests executed (passed, failed)",
    "Build s",
    "Test s",
    "Incremental",
    "Unexpected",
    "Queue",
    "Receipt ok",
)
SELECTED_HEADER = SUMMARY_HEADER + ("Used for",)
GOAL_HEADER = ("Suite", "Check", "Value", "Target", "Status", "Receipt")


def _summary_cells(row: Row) -> list[str]:
    return [
        _suite(row.suite, row.sanitize),
        row.started_at or "?",
        f"`{_sha(row)}`",
        f"{row.built} / {row.planned}",
        _num(row.failed),
        _num(row.blocked),
        ", ".join(row.setup_failed) or "-",
        f"{row.test_targets_built} / {row.test_targets_run} ({row.test_targets_failed}, {row.test_targets_blocked})",
        f"{_num(row.tests_executed)} ({_num(row.tests_passed)}, {_num(row.tests_failed)})",
        _num(row.build_seconds),
        _num(row.test_seconds),
        _incremental(row),
        _num(row.unexpected),
        _num(row.errors_queue),
        "yes" if row.ok else "no",
    ]


def _selected_body(selections: Sequence[Selection]) -> Iterable[list[str]]:
    return (_summary_cells(row) + [used] for s in selections for row, used in s.shown())


def _goal_cells(selection: Selection) -> list[list[str]]:
    body = []
    for g in goal_results(selection):
        target = f"{'>=' if g['at_least'] else '<'} {_num(g['limit'])}"
        met = {True: "met", False: "not yet", None: "not in receipt"}[g["met"]]
        receipt = "-" if g["receipt"] is None else f"{g['receipt_started_at'] or '?'} `{g['receipt_sha'][:12] or '?'}`"
        body.append([_suite(selection.suite, selection.sanitize), g["check"], _num(g["value"]), target, met, receipt])
    return body


def _done_check_tables(selections: Sequence[Selection]) -> list[str]:
    lines = _table(SELECTED_HEADER, _selected_body(selections))
    lines += [""]
    lines += _table(GOAL_HEADER, (c for s in selections for c in _goal_cells(s)))
    return lines


def render_markdown(rows: Sequence[Row], history: int, cases: bool) -> str:
    selections = select(rows)
    out = ["## Linux tier: the receipts the done checks read (p15-oracle.md section 5, checks 1-3)", ""]
    out += _done_check_tables(selections)
    shown = list(rows) if history == 0 else list(rows)[-history:]
    out += ["", f"## History ({len(shown)} of {len(rows)} receipts, oldest first)", ""]
    out += _table(SUMMARY_HEADER, (_summary_cells(r) for r in shown))
    if cases:
        for selection in selections:
            row = selection.totals or selection.newest
            unit = "package" if row.suite == "swift-shared" else "test target"
            out += ["", f"## Tests per {unit}: {_suite(row.suite, row.sanitize)} at `{_sha(row)}`", ""]
            if not row.cases:
                out.append(f"No {unit} ran tests.")
                continue
            out += _table(
                ("Case", "Run", "Tests executed", "[ linux ] share"),
                ([name, run, _num(tests), f"{share:.1%}"] for name, run, tests, share in row.cases),
            )
    out += ["", "Receipts: " + ", ".join(row.path for s in selections for row, _ in s.shown())]
    return "\n".join(out) + "\n"


def render_doc_block(rows: Sequence[Row]) -> str:
    lines = [DOC_BEGIN, ""]
    lines += _done_check_tables(select(rows))
    lines += ["", DOC_END]
    return "\n".join(lines)


def replace_doc_block(text: str, block: str) -> str:
    begin = text.find(DOC_BEGIN)
    end = text.find(DOC_END)
    if begin < 0 or end < begin:
        raise ValueError(f"the doc has no {DOC_BEGIN!r} ... {DOC_END!r} block")
    return text[:begin] + block + text[end + len(DOC_END) :]


def report_json(rows: Sequence[Row]) -> dict:
    def as_dict(row: Row | None) -> dict | None:
        if row is None:
            return None
        d = dataclasses.asdict(row)
        d["cases"] = [{"case": n, "run": r, "tests": t, "linux_share": s} for n, r, t, s in row.cases]
        return d

    return {
        "schema": "cmux-linux-tier-report/1",
        "latest": [
            {
                "suite": s.suite,
                "sanitize": s.sanitize,
                "newest": as_dict(s.newest),
                "totals": as_dict(s.totals),
                "incremental": as_dict(s.incremental),
                "done_checks": goal_results(s),
            }
            for s in select(rows)
        ],
        "history": [as_dict(r) for r in rows],
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("paths", nargs="*", type=Path, help="receipt files or folders to search")
    parser.add_argument("--json", action="store_true", help="print the report as JSON")
    parser.add_argument("--cases", action="store_true", help="list executed tests per test target or package")
    parser.add_argument("--history", type=int, default=20, help="receipts in the history table (0: all)")
    parser.add_argument("--write-doc", nargs="?", const=DESIGN_DOC, type=Path, help="replace the doc's results block")
    args = parser.parse_args(argv)

    warnings: list[str] = []
    paths = args.paths or default_paths(dict(os.environ))
    rows = load_rows(paths, warnings)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    if not rows:
        print(f"error: no {RECEIPT_SCHEMA} receipt under {', '.join(map(str, paths))}", file=sys.stderr)
        return 2
    if args.write_doc:
        try:
            text = args.write_doc.read_text(encoding="utf-8")
            args.write_doc.write_text(replace_doc_block(text, render_doc_block(rows)), encoding="utf-8")
        except (OSError, ValueError) as error:
            print(f"error: {args.write_doc}: {error}", file=sys.stderr)
            return 2
        print(f"wrote the done checks of {len(select(rows))} suite(s) to {args.write_doc}", file=sys.stderr)
    if args.json:
        print(json.dumps(report_json(rows), indent=2, sort_keys=True))
    else:
        sys.stdout.write(render_markdown(rows, args.history, args.cases))
    return 0


if __name__ == "__main__":
    sys.exit(main())
